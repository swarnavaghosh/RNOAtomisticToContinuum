        SUBROUTINE EVAL_PHI(X, Y)
          DOUBLE PRECISION, INTENT(IN)  :: X(NIN)
          DOUBLE PRECISION, INTENT(OUT) :: Y(NSIG)
          DOUBLE PRECISION :: XH(NIN), H1(NH), H2(NH)
          XH = (X - PMUI)/PSI
          H1 = SELU(MATMUL(PW1, XH) + PB1)
          H2 = SELU(MATMUL(PW2, H1) + PB2)
          Y  = (MATMUL(PW3, H2) + PB3)*PSO + PMUO
        END SUBROUTINE

        SUBROUTINE EVAL_BETA(X, Y)
          DOUBLE PRECISION, INTENT(IN)  :: X(NIN)
          DOUBLE PRECISION, INTENT(OUT) :: Y(NXI)
          DOUBLE PRECISION :: XH(NIN), H1(NH), H2(NH)
          XH = (X - BMUI)/BSI
          H1 = SELU(MATMUL(BW1, XH) + BB1)
          H2 = SELU(MATMUL(BW2, H1) + BB2)
          Y  = (MATMUL(BW3, H2) + BB3)*BSO + BMUO
        END SUBROUTINE
      END MODULE RNO_NET

      SUBROUTINE VUMAT(
C     Read only -
     1  NBLOCK, NDIR, NSHR, NSTATEV, NFIELDV, NPROPS, LANNEAL,
     2  STEPTIME, TOTALTIME, DT, CMNAME, COORDMP, CHARLENGTH,
     3  PROPS, DENSITY, STRAININC, RELSPININC,
     4  TEMPOLD, STRETCHOLD, DEFGRADOLD, FIELDOLD,
     5  STRESSOLD, STATEOLD, ENERINTERNOLD, ENERINELASOLD,
     6  TEMPNEW, STRETCHNEW, DEFGRADNEW, FIELDNEW,
C     Write only -
     7  STRESSNEW, STATENEW, ENERINTERNNEW, ENERINELASNEW)
C
      USE RNO_NET
      INCLUDE 'VABA_PARAM.INC'
C
      DIMENSION PROPS(NPROPS), DENSITY(NBLOCK), COORDMP(NBLOCK,*),
     1  CHARLENGTH(NBLOCK), STRAININC(NBLOCK,NDIR+NSHR),
     2  RELSPININC(NBLOCK,NSHR), TEMPOLD(NBLOCK),
     3  STRETCHOLD(NBLOCK,NDIR+NSHR),
     4  DEFGRADOLD(NBLOCK,NDIR+NSHR+NSHR),
     5  FIELDOLD(NBLOCK,NFIELDV), STRESSOLD(NBLOCK,NDIR+NSHR),
     6  STATEOLD(NBLOCK,NSTATEV), ENERINTERNOLD(NBLOCK),
     7  ENERINELASOLD(NBLOCK), TEMPNEW(NBLOCK),
     8  STRETCHNEW(NBLOCK,NDIR+NSHR),
     9  DEFGRADNEW(NBLOCK,NDIR+NSHR+NSHR),
     *  FIELDNEW(NBLOCK,NFIELDV), STRESSNEW(NBLOCK,NDIR+NSHR),
     1  STATENEW(NBLOCK,NSTATEV), ENERINTERNNEW(NBLOCK),
     2  ENERINELASNEW(NBLOCK)
C
      CHARACTER*80 CMNAME
      DOUBLE PRECISION XIN(44), SIG(6), XIDOT(25), XI(25)
      DOUBLE PRECISION FN(9), FO(9), FD(9), E6(6)
      DOUBLE PRECISION EEFF, XNU, TREF, BTQ, RHO, CPH
      DOUBLE PRECISION G2, BLK, TRE, DDISS, SPOW, TRE3, DB2, DIFF
      DOUBLE PRECISION TSCL
      DOUBLE PRECISION GBR(4), TAUB(4), WT6(6)
      INTEGER K, I, IB
      DATA GBR  /3.966239D9, 0.0D0, 390.4472D6, 838.3138D6/
      DATA TAUB /0.05D-6, 1.0D-6, 3.2D-6, 8.0D-6/
      DATA WT6  /1.D0, 1.D0, 1.D0, 2.D0, 2.D0, 2.D0/
      DOUBLE PRECISION DTS
      DOUBLE PRECISION, PARAMETER :: TAUMIN = 0.05D-6
      INTEGER NSUB, ISUB
C
      EEFF = PROPS(1)
      XNU  = PROPS(2)
      TREF = PROPS(3)
      BTQ  = PROPS(5)
      RHO  = PROPS(6)
      CPH  = PROPS(7)
C
      IF (.NOT. LOADED) CALL INIT_WEIGHTS(TREF)
      TSCL = 1.0D0
      IF (NINT(TREF) .EQ. 400) TSCL = 0.95D0
      IF (NINT(TREF) .EQ. 500) TSCL = 0.90D0
C
C     --- Initial elastic step: Abaqus probes the stiffness for the
C         stable time increment estimate at TOTALTIME = 0 ---
      IF (TOTALTIME .LE. DT) THEN
        G2  = EEFF/(1.D0+XNU)
        BLK = EEFF/(3.D0*(1.D0-2.D0*XNU))
        DO K = 1, NBLOCK
          TRE = STRAININC(K,1)+STRAININC(K,2)+STRAININC(K,3)
          DO I = 1, NDIR
            STRESSNEW(K,I) = STRESSOLD(K,I)
     1        + (BLK-G2/3.D0)*TRE + G2*STRAININC(K,I)
          END DO
          DO I = NDIR+1, NDIR+NSHR
            STRESSNEW(K,I) = STRESSOLD(K,I) + G2*STRAININC(K,I)
          END DO
          DO I = 1, NSTATEV
            STATENEW(K,I) = STATEOLD(K,I)
          END DO
          ENERINTERNNEW(K) = ENERINTERNOLD(K)
          ENERINELASNEW(K) = ENERINELASOLD(K)
        END DO
        RETURN
      END IF
C
C     ------------------------- RNO update -------------------------
      DO K = 1, NBLOCK
C       The RNO configuration input is the right stretch tensor U
C       (Abaqus symmetric order 11,22,33,12,23,31), consistent with
C       the corotational stress convention of VUMAT and ensuring
C       frame indifference of the operator inputs.
        CALL SYM2ROW(STRETCHNEW(K,1:6), FN)
        CALL SYM2ROW(STRETCHOLD(K,1:6), FO)
        FD = (FN - FO)/DT
C
        DO I = 1, 25
          XI(I) = STATEOLD(K,I)
        END DO
C
C       xi_n = xi_{n-1} + dt * beta(F_n, Fdot_n, theta, xi_{n-1})
        XIN(1:9)   = FN
        XIN(10:18) = FD
        XIN(19)    = TEMPOLD(K)
        XIN(20:44) = XI
C       Forward-Euler update of the latent internal variables
C       (Eq. 3b), sub-stepped so that the sub-increment remains a
C       fraction of the fastest relaxation time; this preserves the
C       explicit update of the reference formulation while remaining
C       stable when the global time increment exceeds tau_min.
        NSUB = INT(DT/(0.4D0*TAUMIN)) + 1
        IF (NSUB .GT. 60) NSUB = 60
        DTS = DT/DBLE(NSUB)
        DO ISUB = 1, NSUB
          XIN(20:44) = XI
          CALL EVAL_BETA(XIN, XIDOT)
          DO I = 1, 25
            XI(I) = XI(I) + DTS*XIDOT(I)
          END DO
        END DO
        DO I = 1, 25
          STATENEW(K,I) = XI(I)
        END DO
C
C       sigma_n = phi(F_n, Fdot_n, theta, xi_n)
        XIN(20:44) = XI
        CALL EVAL_PHI(XIN, SIG)
C       [11,22,33,12,23,13] -> Abaqus VUMAT order [11,22,33,12,23,31]
        STRESSNEW(K,1) = SIG(1)
        STRESSNEW(K,2) = SIG(2)
        STRESSNEW(K,3) = SIG(3)
        STRESSNEW(K,4) = SIG(4)
        IF (NSHR .GE. 2) STRESSNEW(K,5) = SIG(5)
        IF (NSHR .GE. 3) STRESSNEW(K,6) = SIG(6)
C
C       stress power (per unit mass, Abaqus convention)
        SPOW = 0.D0
        DO I = 1, NDIR
          SPOW = SPOW + 0.5D0*(STRESSOLD(K,I)+STRESSNEW(K,I))
     1                 *STRAININC(K,I)
        END DO
        DO I = NDIR+1, NDIR+NSHR
          SPOW = SPOW + (STRESSOLD(K,I)+STRESSNEW(K,I))
     1                 *STRAININC(K,I)
        END DO
        ENERINTERNNEW(K) = ENERINTERNOLD(K) + SPOW/DENSITY(K)
C       EXACT viscoelastic dissipation rate from the latent state:
C          D = sum_b 2 G_b |e - xi_b|^2 / tau_b   (>= 0 identically)
C       e = deviatoric part of (U - I); branch b occupies xi slots
C       6(b-1)+1 .. 6b, components [11,22,33,12,23,13].
        E6(1) = FN(1) - 1.D0
        E6(2) = FN(5) - 1.D0
        E6(3) = FN(9) - 1.D0
        E6(4) = FN(2)
        E6(5) = FN(6)
        E6(6) = FN(3)
        TRE3  = (E6(1)+E6(2)+E6(3))/3.D0
        E6(1) = E6(1) - TRE3
        E6(2) = E6(2) - TRE3
        E6(3) = E6(3) - TRE3
        DDISS = 0.D0
        DO IB = 1, 4
          DB2 = 0.D0
          DO I = 1, 6
            DIFF = E6(I) - XI(6*(IB-1)+I)
            DB2 = DB2 + WT6(I)*DIFF*DIFF
          END DO
          DDISS = DDISS + 2.D0*GBR(IB)*TSCL/TAUB(IB)*DB2
        END DO
C       DDISS is a RATE (W/m^3); energy this increment = DDISS*DT
        STATENEW(K,26) = STATEOLD(K,26) + DDISS*DT
        STATENEW(K,27) = STATEOLD(K,27) + BTQ*DDISS*DT/(RHO*CPH)
        ENERINELASNEW(K) = ENERINELASOLD(K) + DDISS*DT/DENSITY(K)
        STATENEW(K,40) = 1.D0
      END DO
      RETURN
      END SUBROUTINE VUMAT

      SUBROUTINE SYM2ROW(UA, FR)
C     Abaqus symmetric tensor (11,22,33,12,23,31) -> row-major 3x3
      DOUBLE PRECISION UA(6), FR(9)
      FR(1) = UA(1)
      FR(2) = UA(4)
      FR(3) = UA(6)
      FR(4) = UA(4)
      FR(5) = UA(2)
      FR(6) = UA(5)
      FR(7) = UA(6)
      FR(8) = UA(5)
      FR(9) = UA(3)
      RETURN
      END SUBROUTINE SYM2ROW

      SUBROUTINE A2ROW(FA, FR)
C     Abaqus defgrad vector (11,22,33,12,23,31,21,32,13) -> row major
      DOUBLE PRECISION FA(9), FR(9)
      FR(1) = FA(1)
      FR(2) = FA(4)
      FR(3) = FA(9)
      FR(4) = FA(7)
      FR(5) = FA(2)
      FR(6) = FA(5)
      FR(7) = FA(6)
      FR(8) = FA(8)
      FR(9) = FA(3)
      RETURN
      END SUBROUTINE A2ROW
